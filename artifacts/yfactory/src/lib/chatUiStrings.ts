export function getChatUiStrings(lang: string): ChatUiStrings {
  const lower = lang.trim().toLowerCase();
  const base = lower.split("-")[0] ?? "en";
  const raw = CHAT_STRINGS_MAP[lower] ?? CHAT_STRINGS_MAP[base] ?? CHAT_STRINGS_MAP.en!;
  const prefixAgo = base === "ar" ? "منذ " : base === "fr" ? "il y a " : base === "es" ? "hace " : "";
  return {
    ...raw,
    minsAgo: (n: number) => `${prefixAgo}${n} ${raw.minUnit}`,
    hrsAgo: (n: number) => `${prefixAgo}${n} ${raw.hrUnit}`,
    daysAgo: (n: number) => `${prefixAgo}${n} ${raw.dayUnit}`,
  };
}
